set -e

GRAPHDB=graph
echo "init $GRAPHDB"

PGPASSWORD=$POSTGRES_PASSWORD psql \
    -v ON_ERROR_STOP=1 \
    -U $POSTGRES_USER \
    -d $POSTGRES_DB <<-EOSQL
  CREATE DATABASE $GRAPHDB LC_COLLATE 'C' LC_CTYPE 'C' ENCODING 'UTF8' TEMPLATE template0;
  CREATE USER $GRAPHDB WITH PASSWORD '${POSTGRES_USER_PASSWORD}';
  GRANT CREATE ON DATABASE $GRAPHDB TO $GRAPHDB;
EOSQL

PGPASSWORD=$POSTGRES_PASSWORD psql \
    -v ON_ERROR_STOP=1 \
    -U $POSTGRES_USER \
    -d $GRAPHDB <<-EOSQL
  CREATE EXTENSION pg_trgm;
  CREATE EXTENSION pg_stat_statements;
  CREATE EXTENSION btree_gist;
  CREATE EXTENSION postgres_fdw;
  GRANT USAGE ON FOREIGN DATA WRAPPER postgres_fdw TO $GRAPHDB;
  GRANT ALL PRIVILEGES ON SCHEMA PUBLIC TO $GRAPHDB;
EOSQL
